import { Chip } from "./Chip.ts";
import type { Command } from "./Command.ts";
import { CommandOPLLConfig, CommandOPLLRegister } from "./CommandOPLL.ts";

export class ChipOPLL extends Chip {
	private clockFrequency: number;

	constructor() {
		super(registerMasks);
		this.clockFrequency = 315000000 / 88;
	}

	config(clockFrequency: number) {
		this.clockFrequency = clockFrequency;
	}

	writeCommand(command: Command) {
		if (command instanceof CommandOPLLRegister) {
			this.set(command.address, command.value);
		} else if (command instanceof CommandOPLLConfig) {
			this.config(command.clockFrequency);
		}
	}
}

const registerMasks = [
	0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3F, 0x0F,
	0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
];
