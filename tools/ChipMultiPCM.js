import { Chip } from "./Chip.js";
import { CommandMultiPCMBankRegister, CommandMultiPCMConfig, CommandMultiPCMRegister, CommandMultiPCMWaveMemory } from "./CommandMultiPCM.js";
import { Memory } from "./Memory.js";
import { rangeMap } from "./utils.js";

export class ChipMultiPCM extends Chip {
	constructor() {
		super(registerMasks);
		this.clockFrequency = 33868800;
		this.waveTables = rangeMap(32, i => (i & 0x07) != 0x07 ? new ChipMultiPCMWaveTable() : undefined);
		this.memory = new Memory(new Uint8Array(0x400000));
		this.bankLow = 0x100000;
		this.bankHigh = 0x180000;
	}

	config(clockFrequency) {
		this.clockFrequency = clockFrequency;
	}

	set(address, value, mask = 0xFF) {
		if ((address & 0x7) == 0x7) {
			return false;
		} if (address >= 0x020 && address < 0x040 && mask) {
			super.set(address, value, mask);
			const channel = address & 0x1F;
			const wtAddress = this.getWaveTableAddress(this.getWaveTableNumber(channel));
			let changed = this.updateWaveTable(this.waveTables[channel], wtAddress);
			changed = this.set(0x0C0 + channel, this.memory.get(wtAddress + 7)) || changed;
			changed = this.set(0x100 + channel, this.memory.get(wtAddress + 8)) || changed;
			changed = this.set(0x120 + channel, this.memory.get(wtAddress + 9)) || changed;
			changed = this.set(0x140 + channel, this.memory.get(wtAddress + 10)) || changed;
			changed = this.set(0x0E0 + channel, this.memory.get(wtAddress + 11)) || changed;
			return changed;
		}
		return super.set(address, value, mask);
	}

	unset(address, mask = 0xFF) {
		super.unset(address, mask);
		if (address >= 0x020 && address < 0x040 && mask) {
			this.waveTables[address - 0x020].unset();
		} else if (address >= 0x040 && address < 0x060 && mask & 0x01) {
			this.waveTables[address - 0x040].unset();
		}
	}

	setBank(address, value) {
		if (address == 0x10) {
			this.bankLow = value << 20;
			this.bankHigh = value << 20 | 0x80000;
		} else if (address == 0x11) {
			this.bankLow = value << 19;
		} else if (address == 0x12) {
			this.bankHigh = value << 19;
		}
	}

	updateWaveTable(waveTable, wtAddress) {
		return waveTable.set(
			this.memory.get(wtAddress + 0) << 16 | this.memory.get(wtAddress + 1) << 8 | this.memory.get(wtAddress + 2),
			this.memory.get(wtAddress + 3) << 8 | this.memory.get(wtAddress + 4),
			this.memory.get(wtAddress + 5) << 8 | this.memory.get(wtAddress + 6)
		);
	}

	getWaveTable(channel) {
		return this.waveTables[channel];
	}

	getWaveTableNumber(channel) {
		return this.get(0x040 + channel, 0x01) << 8 | this.get(0x020 + channel);
	}

	getWaveTableAddress(index) {
		if (index < 0 || index >= 0x200)
			throw new Error("Wave table number out of range.");
		return index * 12;
	}

	writeCommand(command) {
		if (command instanceof CommandMultiPCMRegister) {
			this.set(command.address, command.value);
		} else if (command instanceof CommandMultiPCMConfig) {
			this.config(command.clockFrequency);
		} else if (command instanceof CommandMultiPCMWaveMemory) {
			this.memory.setData(command.address, command.memory);
		} else if (command instanceof CommandMultiPCMBankRegister) {
			this.setBank(command.address, command.value);
		}
	}
}

export class ChipMultiPCMWaveTable {
	constructor() {
		this.initialized = false;
		this.start = 0;
		this.loop = 0;
		this.end = 0;
	}

	getBits() {
		return [8, 12, 8, 12][this.start >> 22];
	}

	getStart() {
		return this.start & 0x1FFFFF;
	}

	getLoop() {
		return this.loop;
	}

	getSize() {
		return (this.end ^ 0xFFFF) + 1;
	}

	isSet() {
		return this.initialized;
	}

	set(start, loop, end) {
		const changed = !this.initialized || this.start != start || this.loop != loop || this.end != end;
		this.initialized = true;
		this.start = start;
		this.loop = loop;
		this.end = end;
		return changed;
	}

	unset() {
		this.initialized = false;
	}

	equals(other) {
		return !this.initialized && !other.initialized || this.initialized == other.initialized &&
			this.start == other.start && this.loop == other.loop && this.end == other.end;
	}
}

