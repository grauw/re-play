import { Chip } from "./Chip.ts";
import type { Command } from "./Command.ts";
import { CommandOPL4Config, CommandOPL4Register, CommandOPL4WaveMemory, type OPL4Type } from "./CommandOPL4.ts";
import { Memory } from "./Memory.ts";
import { rangeMap } from "./utils.ts";
import { yrw801Headers } from "./YRW801Headers.ts";

export class ChipOPL4 extends Chip {
	private clockFrequency: number;
	private readonly channels: readonly ChipOPL4Channel[];
	public readonly memory: Memory;

	constructor() {
		super(registerMasks);
		this.clockFrequency = 33868800;
		this.channels = rangeMap(24, i => new ChipOPL4Channel(i));
		const memoryData = new Uint8Array(0x400000);
		memoryData.set(yrw801Headers);
		this.memory = new Memory(memoryData);
	}

	config(clockFrequency: number, type: OPL4Type) {
		this.clockFrequency = clockFrequency * 33868800 / (type == "ymf278b" ? 33868800 : 315000000 / (type == "ymf262" ? 22 : 88));

		if (type == "ymf262" || type == "ym3812" || type == "ym3526" || type == "y8950") {
			for (let address = 0x200; address < 0x300; address++) {
				this.getRegister(address).mask &= 0x00;
			}
		}
		if (type == "ym3812" || type == "ym3526" || type == "y8950") {
			for (let address = 0x0C0; address < 0x0C9; address++) {
				this.getRegister(address).mask &= 0x0F;
				this.getRegister(address).value = 0x30;
			}
			for (let address = 0x0E0; address < 0x100; address++) {
				this.getRegister(address).mask &= 0x03;
			}
			for (let address = 0x100; address < 0x200; address++) {
				this.getRegister(address).mask &= 0x00;
			}
		}
		if (type == "ym3526" || type == "y8950") {
			for (let address = 0x0E0; address < 0x100; address++) {
				this.getRegister(address).mask &= 0x00;
			}
		}
	}

	set(address: number, value: number, mask = 0xFF): boolean {
		if (address == 0x004 && value & mask & 0x80) {
			return true;
		} else if (address >= 0x208 && address < 0x220 && mask) {
			super.set(address, value, mask);
			const channel = address - 0x208;
			const wtAddress = this.getWaveTableAddress(this.getWaveTableNumber(channel));
			let changed = this.updateWaveTable(this.channels[channel].waveTable, wtAddress);
			changed = this.set(0x280 + channel, this.memory.get(wtAddress + 7)) || changed;
			changed = this.set(0x298 + channel, this.memory.get(wtAddress + 8)) || changed;
			changed = this.set(0x2B0 + channel, this.memory.get(wtAddress + 9)) || changed;
			changed = this.set(0x2C8 + channel, this.memory.get(wtAddress + 10)) || changed;
			changed = this.set(0x2E0 + channel, this.memory.get(wtAddress + 11)) || changed;
			return changed;
		}
		return super.set(address, value, mask);
	}

	unset(address: number, mask = 0xFF) {
		super.unset(address, mask);
		if (address >= 0x208 && address < 0x220 && mask) {
			this.channels[address - 0x208].waveTable.unset();
		} else if (address >= 0x220 && address < 0x238 && mask & 0x01) {
			this.channels[address - 0x220].waveTable.unset();
		}
	}

	getChannel(index: number) {
		return this.channels[index];
	}

	updateWaveTable(waveTable: ChipOPL4WaveTable, wtAddress: number) {
		return waveTable.set(
			this.memory.get(wtAddress + 0) << 16 | this.memory.get(wtAddress + 1) << 8 | this.memory.get(wtAddress + 2),
			this.memory.get(wtAddress + 3) << 8 | this.memory.get(wtAddress + 4),
			this.memory.get(wtAddress + 5) << 8 | this.memory.get(wtAddress + 6)
		);
	}

	getWaveTable(index: number) {
		const waveTable = new ChipOPL4WaveTable();
		this.updateWaveTable(waveTable, this.getWaveTableAddress(index));
		return waveTable;
	}

	getWaveTableNumber(channel: number) {
		return this.get(0x220 + channel, 0x01) << 8 | this.get(0x208 + channel);
	}

	getWaveTableAddress(index: number) {
		if (index < 0 || index >= 0x200)
			throw new Error("Wave table number out of range.");
		const area = this.get(0x202) >> 2 & 0x07;
		return area == 0 || index < 0x180 ? index * 12 : area * 0x80000 + (index - 0x180) * 12;
	}

	writeCommand(command: Command) {
		if (command instanceof CommandOPL4Register) {
			this.set(command.address, command.value);
		} else if (command instanceof CommandOPL4Config) {
			this.config(command.clockFrequency, command.type);
		} else if (command instanceof CommandOPL4WaveMemory) {
			this.memory.setData(command.address, command.memory);
		}
	}
}

export class ChipOPL4Channel {
	private readonly index: number;
	public readonly waveTable: ChipOPL4WaveTable;

	constructor(index: number) {
		this.index = index;
		this.waveTable = new ChipOPL4WaveTable();
	}
}

export class ChipOPL4WaveTable {
	private initialized: boolean;
	public start: number;
	public loop: number;
	public end: number;

	constructor() {
		this.initialized = false;
		this.start = 0;
		this.loop = 0;
		this.end = 0;
	}

	getBits() {
		return [8, 12, 16, 0][this.start >> 22];
	}

	getStart() {
		return this.start & 0x3FFFFF;
	}

	getLoop() {
		return this.loop;
	}

	getSize() {
		return (this.end ^ 0xFFFF) + 1;
	}

	getEnd(padding = 0) {
		return this.getStart() + Math.ceil((this.getSize() + padding) * this.getBits() / 8);
	}

	isSet() {
		return this.initialized;
	}

	set(start: number, loop: number, end: number) {
		const changed = !this.initialized || this.start != start || this.loop != loop || this.end != end;
		this.initialized = true;
		this.start = start;
		this.loop = loop;
		this.end = end;
		return changed;
	}

	unset() {
		this.initialized = false;
	}

	equals(other: ChipOPL4WaveTable) {
		return !this.initialized && !other.initialized || this.initialized == other.initialized &&
			this.start == other.start && this.loop == other.loop && this.end == other.end;
	}
}

